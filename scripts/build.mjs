import { readFile, writeFile } from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const ui = await readFile(new URL('src/ui.js', root), 'utf8');
const time = await readFile(new URL('src/time.js', root), 'utf8');
const browserTime = `window.DSHTodoTime = (() => {\n${time.replace(/^export /gm, '')}\nreturn { sortTodos, formatCountdown };\n})();\n`;
const template = await readFile(new URL('src/client-template.js', root), 'utf8');
const theme = await readFile(new URL('src/theme.js', root), 'utf8');
const output = '// Generated by scripts/build.mjs. Edit src/ui.js, src/time.js, src/theme.js or src/client-template.js.\n' + template.replace('/* TODO_UI */', () => browserTime + ui).replace('/* TODO_THEME */', () => theme.replace(/^export /gm, ''));
if (process.argv.includes('--check')) {
  if (await readFile(new URL('client.js', root), 'utf8') !== output) throw new Error('client.js is stale; run npm run build');
  if (await readFile(new URL('native/time.js', root), 'utf8') !== browserTime) throw new Error('native/time.js is stale; run npm run build');
} else {
  await writeFile(new URL('client.js', root), output);
  await writeFile(new URL('native/time.js', root), browserTime);
}
